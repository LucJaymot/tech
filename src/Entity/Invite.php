<?php

namespace App\Entity;

use App\Enum\ResultatPointage;
use App\Repository\InviteRepository;
use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;
use Symfony\Component\Validator\Constraints as Assert;

/**
 * A guest on a guest list, checked in at the door.
 *
 * A check-in carries the id and time given by the door device. When two
 * devices check the same guest in, the earliest check-in wins.
 */
#[ORM\Entity(repositoryClass: InviteRepository::class)]
#[ORM\UniqueConstraint(name: 'UNIQ_INVITE_POINTAGE', fields: ['pointageId'])]
class Invite implements CollectiveScopedInterface
{
    public const int ACCOMPAGNANTS_MAX = 10;

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column]
    private ?int $id = null;

    #[ORM\ManyToOne(inversedBy: 'invites')]
    #[ORM\JoinColumn(nullable: false, onDelete: 'CASCADE')]
    private GuestList $guestList;

    /** Copied from the list, for the collective filter. */
    #[ORM\ManyToOne]
    #[ORM\JoinColumn(nullable: false, onDelete: 'CASCADE')]
    private Collective $collective;

    #[ORM\Column(length: 120)]
    #[Assert\NotBlank(message: 'Indiquez le nom de l\'invité.')]
    #[Assert\Length(max: 120)]
    private string $nom;

    #[ORM\Column]
    #[Assert\Range(min: 0, max: self::ACCOMPAGNANTS_MAX)]
    private int $accompagnants;

    #[ORM\Column]
    private \DateTimeImmutable $ajouteLe;

    /** When the guest was checked in, as given by the door device. */
    #[ORM\Column(nullable: true)]
    private ?\DateTimeImmutable $pointeAt = null;

    #[ORM\ManyToOne]
    #[ORM\JoinColumn(onDelete: 'SET NULL')]
    private ?User $pointePar = null;

    /** Id generated by the door device for the winning check-in. */
    #[ORM\Column(type: Types::GUID, nullable: true)]
    private ?string $pointageId = null;

    public function __construct(GuestList $guestList, string $nom, int $accompagnants = 0)
    {
        $this->guestList = $guestList;
        $this->collective = $guestList->getCollective();
        $this->nom = trim($nom);
        $this->accompagnants = $accompagnants;
        $this->ajouteLe = new \DateTimeImmutable();

        $guestList->getInvites()->add($this);
    }

    /**
     * Applies a check-in received from a door device; the earliest one wins.
     * Sending the same check-in again changes nothing.
     */
    public function pointer(string $pointageId, \DateTimeImmutable $at, ?User $par): ResultatPointage
    {
        if ($pointageId === $this->pointageId) {
            return ResultatPointage::DejaEnregistre;
        }
        if (null !== $this->pointeAt && $this->pointeAt <= $at) {
            return ResultatPointage::Conflit;
        }

        $this->pointageId = $pointageId;
        $this->pointeAt = $at;
        $this->pointePar = $par;

        return ResultatPointage::Accepte;
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getGuestList(): GuestList
    {
        return $this->guestList;
    }

    public function getCollective(): Collective
    {
        return $this->collective;
    }

    public function getNom(): string
    {
        return $this->nom;
    }

    public function getAccompagnants(): int
    {
        return $this->accompagnants;
    }

    /**
     * The guest and their companions.
     */
    public function personnes(): int
    {
        return 1 + $this->accompagnants;
    }

    public function getAjouteLe(): \DateTimeImmutable
    {
        return $this->ajouteLe;
    }

    public function estPointe(): bool
    {
        return null !== $this->pointeAt;
    }

    public function getPointeAt(): ?\DateTimeImmutable
    {
        return $this->pointeAt;
    }

    public function getPointePar(): ?User
    {
        return $this->pointePar;
    }

    public function getPointageId(): ?string
    {
        return $this->pointageId;
    }
}
